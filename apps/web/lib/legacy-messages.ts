export function translateLegacyText(locale: AppLocale, input: string): string {
  if (locale === 'pt-PT') return input;
  const leading = input.match(/^\s*/)?.[0] ?? '';
  const trailing = input.match(/\s*$/)?.[0] ?? '';
  const core = input.trim();
  if (!core) return input;
  let translated = enUS[core] ?? core;
  for (const [pattern, replacement] of substitutions) translated = translated.replace(pattern, replacement);
  return `${leading}${translated}${trailing}`;
}

