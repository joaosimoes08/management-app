// The single documented exception to en == translateSourceText: the Tipo filter showed "Servidores" and
// "Outros" untranslated in English; they now read "Servers" and "Other".
const englishFixes: Record<string, string> = {
  'infrastructure.deviceFilters.type.servers': 'Servers',
  'infrastructure.deviceFilters.type.otherTypes': 'Other',
};

const sourceFiles = (dir: string): string[] => readdirSync(dir).flatMap((name) => {
  const path = join(dir, name);
  if (statSync(path).isDirectory()) return name === '__fixtures__' ? [] : sourceFiles(path);
  return /\.tsx?$/.test(name) && !/\.test\./.test(name) ? [path] : [];
});
const files = sourceFiles(__dirname);

describe('infrastructure keyed messages', () => {
  it.each(keyed)('%s renders the same Portuguese and English as before', (key, portuguese, params) => {
    expect(translateMessage('pt-PT', key, undefined, params)).toBe(portuguese);
    const english = translateMessage('en-US', key, undefined, params);
    expect(english).not.toBe(key);
    if (key in englishFixes) expect(english).toBe(englishFixes[key]);
  });

  it('shows the Tipo filter as Servers and Other in English, unchanged in Portuguese', () => {
    const english = (key: string, fallback?: string, params?: Record<string, string | number>) => translateMessage('en-US', key, fallback, params);
    expect(deviceTypeOptions(english)).toEqual([['SWITCH', 'Switches'], ['ROUTER', 'Routers'], ['FIREWALL', 'Firewalls'], ['SERVER', 'Servers'], ['STORAGE', 'Storage'], ['OTHER', 'Other']]);
    expect(deviceTypeOptions()).toEqual([['SWITCH', 'Switches'], ['ROUTER', 'Routers'], ['FIREWALL', 'Firewalls'], ['SERVER', 'Servidores'], ['STORAGE', 'Storage'], ['OTHER', 'Outros']]);
    expect(deviceFilterLabels({ status: '', critical: '', lifecycle: '', lifecycleKind: '', tier: '', tag: '', type: 'SERVER' }, undefined, english)).toEqual(['Tipo: Servers']);
    const servers = 'infrastructure.deviceFilters.type.servers';
    const other = 'infrastructure.deviceFilters.type.otherTypes';
    expect([esES, frFR, deDE, itIT].map((bundle) => [bundle[servers], bundle[other]])).toEqual([['Servidores', 'Otros'], ['Serveurs', 'Autres'], ['Server', 'Andere'], ['Server', 'Altri']]);
  });

  it('covers every key the infrastructure components use, in both locales and the added languages', () => {
    const used = new Set(files.flatMap((file) => [...readFileSync(file, 'utf8').matchAll(/'(infrastructure\.[\w.]+)'/g)].map((match) => match[1])));
    expect([...used].sort()).toEqual([...new Set(keyed.map(([key]) => key))].sort());
    for (const [key, , params] of keyed) {
      for (const locale of ['pt-PT', 'en-US'] as AppLocale[]) expect(translateMessage(locale, key, '∅', params)).not.toBe('∅');
      const forms = keyed.filter(([other]) => other === key).length > 1 ? [`${key}.one`, `${key}.other`] : [key];
      for (const bundle of [esES, frFR, deDE, itIT]) for (const form of forms) expect(bundle[form], form).toBeTruthy();
    }
  });

  // Left on purpose: fallbacks of keys that already exist in i18n.tsx (never shown, the key wins), and the
  // API's own Portuguese value names in types.ts.
  const allowed: Record<string, string[]> = {
    'components/editors/device-power-fields.tsx': ["'padrão'", "'{min} a {max}. 0 = sem alimentação (ex.: patch panel).'"],
    'components/editors/device-power-step.tsx': ["'Ligações elétricas · {device}'", "'Ligações elétricas'", "'O equipamento mudou de bastidor: as ligações anteriores foram removidas.'", "'Sem alimentação: este equipamento não tem fichas.'", "'Escolhe a PDU de cada ficha. A tomada livre seguinte é atribuída automaticamente.'", "'Não ligado'", "'Sem tomadas livres em {pdu}: a ficha fica “Não ligado”.'", "'{count} ficha(s) sem ligação. Podes guardar na mesma.'", "'Este bastidor não tem UPS: o equipamento não tem alimentação redundante.'", "'Agora não'", "'Guardar ligações'"],
    'components/editors/rack-power-fields.tsx': ["'Só rede elétrica'", "'Alimentação'", "'Alimentação'", "'Definições da {name}'", "'Potência máxima (W)'", "'Por omissão {watts} W. Os valores são estimativas e nunca bloqueiam a gravação.'", "'Não é possível remover a UPS: estes equipamentos ainda estão ligados à PDU UPS.'", "'A alteração deixaria equipamentos sem tomada. Desliga-os ou muda-os para tomadas livres primeiro.'"],
    'components/rack/rack-pdu-strip.tsx': ["'Não foi possível desligar o equipamento.'", "'Só leitura'"],
    'types.ts': ["'padrão'"],
  };

  it('leaves no Portuguese literal in the infrastructure source files', () => {
    const found: Record<string, string[]> = {};
    for (const file of files) {
      const source = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\/|(^|[^:'"`])\/\/.*$/gm, '$1');
      const literals = [...source.matchAll(/'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\]|\\.)*`|>([^<>{}]+)</g)]
        .map((match) => match[1] ?? match[0])
        .filter((text) => /[áàãâéêíóôõúçÁÀÃÂÉÊÍÓÔÕÚÇ]/.test(text));
      if (literals.length) found[relative(__dirname, file)] = literals;
    }
    expect(found).toEqual(allowed);
  });
});
